import assert from 'node:assert/strict';
import { chromium } from 'playwright-core';
import { pathToFileURL } from 'node:url';
const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH ?? 'C:/Program Files/Google/Chrome/Application/chrome.exe' });
const page = await browser.newPage({ viewport: { width: 1500, height: 950 } });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
const app = page.locator('#app');
try {
  await page.goto(pathToFileURL('tmp/build/preview.html').href);
  await app.locator('[data-action=scan]').click();
  await page.waitForFunction(() => document.querySelector('#app .toolbar .progress')?.textContent?.includes('마지막 검토'));
  for (const head of await app.locator('.group-head[aria-expanded=false]').all()) await head.click();
  await app.locator('.row').first().waitFor();
  await app.locator('.row').first().click();
  await app.locator('.row').first().locator('[data-action=include]').check();
  await app.locator('[data-action=category-manage]').waitFor();
  assert.equal(await app.locator('[data-action=begin-add][data-kind=category]').count(), 0);
  assert.equal(await app.locator('[data-action=begin-edit][data-kind=category]').count(), 0);
  await app.locator('[data-action=category-manage]').click();
  await app.locator('.admin-nav-item[data-key="카테고리"]').waitFor();
  assert.equal(await app.locator('.admin-nav-item[data-key="Screen ID"]').count(), 0);
  const add = app.locator('[data-form=cat-add]');
  await add.locator('[data-f=name]').fill('Home');
  await add.locator('[data-f=code]').fill('HO');
  await add.locator('[data-action=admin-cat-add]').click();
  const category = app.locator('[data-form=cat-code]').filter({ has: page.locator('[data-f=name][value="Home"]') });
  await category.waitFor();
  const id = await category.getAttribute('data-id');
  await category.locator('[data-f=name]').fill('Home English');
  await category.locator('[data-f=code]').fill('HM');
  await category.locator('[data-action=admin-cat-save]').click();
  const saved = app.locator(`[data-form=cat-code][data-id="${id}"]`);
  await page.waitForFunction(id => document.querySelector(`[data-form=cat-code][data-id="${id}"] [data-f=name]`)?.value === 'Home English', id);
  assert.equal(await saved.locator('[data-f=code]').inputValue(), 'HM');
  await app.locator('[data-action=settings]').click();
  assert.equal(await app.locator('[data-field=categoryId]').inputValue(), id, 'adding through manage selects it for the original draft');
  assert.equal(await app.locator('[data-field=categoryId] option:checked').innerText(), 'Home English');
  await app.locator('[data-action=category-manage]').click();
  await app.screenshot({ path: 'tmp/category-management.png' });
  await saved.locator('[data-action=admin-cat-delete]').click();
  assert.equal(await saved.count(), 1, 'first delete click only arms removal');
  await saved.locator('[data-action=admin-cat-delete]').click();
  await saved.waitFor({ state: 'detached' });
  assert.deepEqual(errors, []);
  console.log('Category UI: manage link, renamed menu, add/edit/delete and original draft selection passed');
} finally { await browser.close(); }
